"""T4.7 entry point: score the golden set and regenerate `docs/llm_eval.md`.

    uv run python scripts/make_llm_eval.py             # rewrite docs/llm_eval.md
    uv run python scripts/make_llm_eval.py --timings   # also print wall-clock, to stdout

CI runs this and then fails on any diff against the committed file, the same gate
`make_results.py` is under. That is what "CI-generated" has to mean here: not that a script
exists, but that a stranger's fork regenerates the identical document.

### Why no wall-clock number is written into the document

The document is byte-diffed. A wall-clock measurement is different on every machine, so
writing one in would make the gate fail on a fast laptop and pass on a slow CI runner, and
the usual fix -- rounding until it stops moving -- is a number that has been rounded until
it stopped meaning anything.

So the p95 latency T4.7 asks for comes from **cassette-recorded** latencies, which are
fixed once recorded and are a measurement of the recording session rather than of this
run. There are no cassettes yet, so that row says so. `--timings` prints the rules path's
wall-clock to stdout for local use, where it is a real number about this machine and is
allowed to vary.

### Two arms, and only one of them has anything to score

* **Rules arm.** 114 structured cases through the deterministic engine. Every number here
  is measured, on every run, by anyone.
* **Model arm.** 6 free-text records that need extraction before they can be judged. No
  cassette has been recorded (`docs/limitations.md` §8.5), so this arm reports as unscored.
  It is not skipped and it is not filled in with a plausible figure.
"""

from __future__ import annotations

import argparse
import json
import time
from collections import Counter, defaultdict
from pathlib import Path

from mandateguard.agent.auditor import MandateAuditor, RulesAuditor
from mandateguard.agent.client import CassetteMissError, build_client
from mandateguard.models import MandateAuditContext, Verdict
from mandateguard.policy.loader import load_params, load_policy, policy_hash

ROOT = Path(__file__).resolve().parents[1]
GOLDEN_PATH = ROOT / "tests" / "golden" / "mandates.jsonl"
OUT_PATH = ROOT / "docs" / "llm_eval.md"

VERDICTS = [Verdict.COMPLIANT, Verdict.NON_COMPLIANT, Verdict.NEEDS_HUMAN]


def load_cases() -> list[dict]:
    lines = GOLDEN_PATH.read_text(encoding="utf-8").splitlines()
    return [json.loads(line) for line in lines if line.strip()]


def score_rules(cases: list[dict], auditor: RulesAuditor) -> tuple[list[dict], float]:
    """Run every rules case. Returns the per-case results and the wall-clock seconds."""
    results = []
    started = time.perf_counter()
    for case in cases:
        verdict = auditor.audit(MandateAuditContext.model_validate(case["context"]))
        results.append(
            {
                "case": case,
                "got_verdict": verdict.verdict,
                "got_citations": sorted(set(verdict.citations)),
            }
        )
    elapsed = time.perf_counter() - started
    return results, elapsed


def _is_exact(result: dict) -> bool:
    """The verdict matches AND it rests on exactly the expected clauses."""
    return (
        result["got_verdict"].value == result["case"]["expected_verdict"]
        and result["got_citations"] == result["case"]["expected_citations"]
    )


def _rate(numerator: int, denominator: int) -> str:
    """A percentage, or an explicit dash. `0/0` is not 0% and must not print as one."""
    if denominator == 0:
        return "—"
    return f"{100.0 * numerator / denominator:.1f}%"


def render(cases: list[dict], results: list[dict], unrecorded: list[str]) -> str:
    policy = load_policy()
    params = load_params()
    rules_cases = [c for c in cases if c["requires"] == "rules"]
    extraction_cases = [c for c in cases if c["requires"] == "extraction"]

    correct_verdict = [
        r for r in results if r["got_verdict"].value == r["case"]["expected_verdict"]
    ]
    exact = [r for r in correct_verdict if r["got_citations"] == r["case"]["expected_citations"]]

    expected_abstain = [r for r in results if r["case"]["expected_verdict"] == Verdict.NEEDS_HUMAN]
    got_abstain = [r for r in results if r["got_verdict"] is Verdict.NEEDS_HUMAN]
    true_abstain = [r for r in got_abstain if r["case"]["expected_verdict"] == Verdict.NEEDS_HUMAN]

    out: list[str] = []
    add = out.append

    add("# LLM eval — the golden set, scored")
    add("")
    add("Generated by `scripts/make_llm_eval.py`. Do not edit: CI regenerates this file and")
    add("fails on any difference, so a hand-typed number here breaks the build rather than")
    add("surviving in it.")
    add("")
    add(f"Policy `{policy_hash()}` · {len(policy.rules)} rules from {policy.source.circular_no} ·")
    add(f"model configured as `{params.llm.model}` at effort `{params.llm.effort}`")
    add("")
    add("---")
    add("")

    # ---------------------------------------------------------------- the set
    add("## 1. What is being scored")
    add("")
    add(f"`tests/golden/mandates.jsonl` — **{len(cases)} cases**, expectations written from")
    add("the circular text rather than read off the auditor. §5 says what that is worth and")
    add("what it is not.")
    add("")
    add("| arm | cases | judged by | scored here |")
    add("|---|---|---|---|")
    add(
        f"| rules | {len(rules_cases)} | the compiled rulebook, deterministically | "
        f"**yes**, every run |"
    )
    add(
        f"| extraction | {len(extraction_cases)} | a model reading free text, then the rules | "
        f"**no** — {len(unrecorded)} unrecorded |"
    )
    add("")
    mix = Counter(c["expected_verdict"] for c in cases)
    add("Expected-verdict mix across the whole set:")
    add("")
    add("| verdict | cases |")
    add("|---|---|")
    for verdict in VERDICTS:
        add(f"| `{verdict.value}` | {mix.get(verdict.value, 0)} |")
    add("")

    # ---------------------------------------------------------------- accuracy
    add("## 2. Accuracy, on the rules arm")
    add("")
    add("| metric | value | what it counts |")
    add("|---|---|---|")
    add(
        f"| Verdict accuracy | **{_rate(len(correct_verdict), len(results))}** "
        f"({len(correct_verdict)}/{len(results)}) | the verdict matches the expectation |"
    )
    add(
        f"| Verdict **and** citations | **{_rate(len(exact), len(results))}** "
        f"({len(exact)}/{len(results)}) | and it rests on exactly the expected clauses |"
    )
    add("")
    add("The second row is the one that matters. A verdict that is right for the wrong")
    add("clause is a finding nobody can act on, and it reads identically to a correct one in")
    add("every summary that counts verdicts alone.")
    add("")

    add("### 2.1 Confusion matrix")
    add("")
    add("| expected \\ got | " + " | ".join(f"`{v.value}`" for v in VERDICTS) + " |")
    add("|---|" + "---|" * len(VERDICTS))
    matrix: dict[str, Counter] = defaultdict(Counter)
    for result in results:
        matrix[result["case"]["expected_verdict"]][result["got_verdict"].value] += 1
    for expected in VERDICTS:
        row = matrix[expected.value]
        cells = " | ".join(str(row.get(got.value, 0)) for got in VERDICTS)
        add(f"| `{expected.value}` | {cells} |")
    add("")

    # ---------------------------------------------------------------- abstention
    add("## 3. Abstention, measured in both directions")
    add("")
    add("Abstain recall alone is a metric a broken system wins: abstain on everything and it")
    add("reaches 100%. Precision is the half that costs something — every abstention is a")
    add("person's time, and a system that abstains on mandates it could have graded is a")
    add("review queue rather than a product.")
    add("")
    add("| metric | value | reading |")
    add("|---|---|---|")
    add(
        f"| Abstain recall | **{_rate(len(true_abstain), len(expected_abstain))}** "
        f"({len(true_abstain)}/{len(expected_abstain)}) | of the cases that should abstain, "
        "how many did |"
    )
    add(
        f"| Abstain precision | **{_rate(len(true_abstain), len(got_abstain))}** "
        f"({len(true_abstain)}/{len(got_abstain)}) | of the cases it abstained on, how many "
        "should have |"
    )
    add("")
    add("On the rules arm every abstention comes from clause 2 — the mandate's rail is")
    add("outside the framework — so this arm measures whether scope is applied correctly,")
    add("not whether the system knows when it is uncertain. The uncertainty half is the")
    add("extraction arm, and it is unscored (§5).")
    add("")

    # ---------------------------------------------------------------- the gap
    add("## 3.1 Natural versus adversarial — GATE 4's honesty number")
    add("")
    add("The gap between how a system scores on ordinary cases and how it scores on cases")
    add("written to break it. A system tuned against its own test set closes the first")
    add("number and not the second, so the difference is the part that is hard to fake.")
    add("")
    natural = [r for r in results if r["case"]["family"] == "natural"]
    adversarial = [r for r in results if r["case"]["family"] == "adversarial"]
    natural_ok = [r for r in natural if _is_exact(r)]
    adversarial_ok = [r for r in adversarial if _is_exact(r)]
    natural_rate = 100.0 * len(natural_ok) / len(natural) if natural else 0.0
    adversarial_rate = 100.0 * len(adversarial_ok) / len(adversarial) if adversarial else 0.0
    add("| set | cases | exact (verdict **and** citations) |")
    add("|---|---|---|")
    add(f"| Natural | {len(natural)} | {_rate(len(natural_ok), len(natural))} |")
    add(f"| Adversarial | {len(adversarial)} | {_rate(len(adversarial_ok), len(adversarial))} |")
    add(f"| **Gap** | — | **{natural_rate - adversarial_rate:+.1f} points** |")
    add("")
    add("**T4.8, the adversarial generator, is cut.** It is CUT #2 in `docs/tasks.md`, and")
    add("the reason it is cut is the reason it could not have been faked: a generator's")
    add("whole value is producing the cases nobody thought of, and there is no credential")
    add("here to run one with. What survives is the measurement — 55 of the 120 cases were")
    add("written adversarially on purpose, against the boundaries T4.8 names (Rs.14,999 vs")
    add("Rs.15,001, the FASTag/NCMC exemption, a mid-cycle modification, a pre-2026")
    add("grandfathered mandate, the Rs.1 lakh cap, a variable mandate with a customer cap),")
    add("and `scripts/build_golden.py` states the criterion that sorts them.")
    add("")
    add("The gap above is therefore a real number about a *hand-written* adversarial set,")
    add("not about a generated one. A generated set would be harder, and the honest reading")
    add("is that this gap is a floor on the true one rather than an estimate of it.")
    add("")

    # ---------------------------------------------------------------- clauses
    add("## 4. Per-clause coverage")
    add("")
    add("Which clauses the set actually exercises, and how each one scores. A clause with")
    add("no cases is a clause nothing has ever tested.")
    add("")
    per_clause_total: Counter = Counter()
    per_clause_ok: Counter = Counter()
    for result in results:
        clauses = set(result["case"]["expected_citations"]) or {"(none — compliant)"}
        ok = (
            result["got_verdict"].value == result["case"]["expected_verdict"]
            and result["got_citations"] == result["case"]["expected_citations"]
        )
        for clause in clauses:
            per_clause_total[clause] += 1
            if ok:
                per_clause_ok[clause] += 1

    add("| clause | cases | exact |")
    add("|---|---|---|")
    for clause in sorted(per_clause_total, key=_clause_sort_key):
        add(
            f"| {clause} | {per_clause_total[clause]} | "
            f"{_rate(per_clause_ok[clause], per_clause_total[clause])} |"
        )
    add("")
    cited = {c for c in per_clause_total if c[0].isdigit()}
    compiled = {rule.clause for rule in policy.rules}
    untested = sorted(compiled - cited, key=_clause_sort_key)
    if untested:
        add(f"**Compiled but never exercised:** {', '.join(untested)}.")
    else:
        add("**Every compiled clause has at least one case.**")
    add("")

    # ---------------------------------------------------------------- model arm
    add("## 5. The model arm, and what it does not say")
    add("")
    add(f"{len(extraction_cases)} cases need a model to read a free-text record before the")
    add("rules can judge it. Each one's expected verdict is an abstention, because the")
    add("record genuinely does not determine a field that an applicable rule reads.")
    add("")
    add("| metric | value |")
    add("|---|---|")
    add(f"| Cases scored | **0 of {len(extraction_cases)}** |")
    add("| Cost per verdict | **not measured** |")
    add("| p95 latency | **not measured** |")
    add("| Accuracy, abstain precision/recall | **not measured** |")
    add("")
    add("The reason is a single fact and it is not a limitation of the design: no Anthropic")
    add("credential was available on the machine where Phase 4 was built, so")
    add("`tests/cassettes/` is empty and every extraction request raises a cassette miss.")
    add("The rows above are blank rather than estimated. A cost-per-verdict figure derived")
    add("from a token count nobody measured would be the exact failure `calibration.md` §5")
    add("exists to prevent.")
    add("")
    add("What **is** known, and is a fact about the code rather than a measurement:")
    add("")
    add("* every request carries its own token counts back from the API and is priced at the")
    add("  rates in `config/params.yaml`, so cost per verdict is measured the moment a")
    add("  cassette exists — it is not estimated then either;")
    add("* the Batch API halves that cost, which is why T4.7 specifies it for a 120-case run;")
    add("* `llm.spend_cap_usd_per_run` stops a run before it exceeds its budget;")
    add("* replayed latency is the latency that was *recorded*, so the p95 this table will")
    add("  eventually carry is a measurement of one machine and one network on one day, and")
    add("  will be labelled as such.")
    add("")
    if unrecorded:
        add("Unrecorded cases:")
        add("")
        for case_id in unrecorded:
            add(f"* `{case_id}`")
        add("")

    # ---------------------------------------------------------------- honesty
    add("## 6. What 100% on the rules arm is worth")
    add("")
    add("Less than it looks, and the reason is worth stating plainly.")
    add("")
    add("**The same reader wrote both sides.** The twenty rules and the 114 expectations were")
    add("written in the same session, from the same reading of the same circular. A")
    add("misreading of clause 8(b) would have gone into the rule *and* into the expectation,")
    add("and this table would show 100% either way. That is not what an independent test set")
    add("means, and this number must not be presented as one.")
    add("")
    add("What the set is genuinely worth is **forward-looking**: it is 120 statements about")
    add("what the circular requires, written down before anyone had a reason to want a")
    add("particular answer. The next time a rule is edited — a threshold moved, a guard")
    add("loosened — this file is what notices. That is a regression suite with citations,")
    add("and it is a real thing to have. It is not external validation.")
    add("")
    add("**The extraction arm is where the model would actually be tested**, and it is the")
    add("arm with no numbers. So this document currently measures a rule engine, not an LLM")
    add("system, and its title overstates it until a cassette exists.")
    add("")
    add("Related: [`limitations.md`](./limitations.md) §8 · [`calibration.md`](./calibration.md)")
    add("§1 and §1.3 · [`eval.md`](./eval.md) for the allocator's own results.")
    return "\n".join(out) + "\n"


def _clause_sort_key(clause: str) -> tuple[int, str]:
    head = clause.split("(")[0]
    return (int(head) if head.isdigit() else 999, clause)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--timings",
        action="store_true",
        help="print wall-clock to stdout; never written to the document",
    )
    args = parser.parse_args()

    cases = load_cases()
    rules_cases = [c for c in cases if c["requires"] == "rules"]
    extraction_cases = [c for c in cases if c["requires"] == "extraction"]

    results, elapsed = score_rules(rules_cases, RulesAuditor())

    # The extraction arm is attempted rather than assumed absent: if someone records
    # cassettes, this loop starts scoring without anyone editing the script.
    unrecorded: list[str] = []
    auditor = MandateAuditor(client=build_client(load_params().llm))
    for case in extraction_cases:
        try:
            auditor.audit_record(case["case_id"], case["record"])
        except CassetteMissError:
            unrecorded.append(case["case_id"])

    OUT_PATH.write_text(render(cases, results, unrecorded), encoding="utf-8")

    wrong = [
        r
        for r in results
        if r["got_verdict"].value != r["case"]["expected_verdict"]
        or r["got_citations"] != r["case"]["expected_citations"]
    ]
    print(f"wrote {OUT_PATH.relative_to(ROOT)}")
    print(f"  rules arm: {len(results) - len(wrong)}/{len(results)} exact")
    print(f"  extraction arm: 0/{len(extraction_cases)} scored ({len(unrecorded)} unrecorded)")
    for result in wrong:
        case = result["case"]
        print(
            f"  MISMATCH {case['case_id']}: expected {case['expected_verdict']} "
            f"{case['expected_citations']}, got {result['got_verdict'].value} "
            f"{result['got_citations']}"
        )
    if args.timings:
        per_case_ms = 1000.0 * elapsed / max(len(results), 1)
        print(
            f"  wall-clock: {elapsed:.3f}s for {len(results)} cases "
            f"({per_case_ms:.2f} ms/case on this machine, not written to the document)"
        )
    return 1 if wrong else 0


if __name__ == "__main__":
    raise SystemExit(main())
